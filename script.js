// สร้างรูปภาพสำรอง (Placeholder) อัตโนมัติในกรณีที่หาไฟล์รูปไม่เจอ
const getPlaceholderImage = (name) => 
    `https://placehold.co/600x400/315c39/ffffff?text=${encodeURIComponent(name)}`;

// แสดงการ์ดรายการพืช
function displayPlants(list) {
    plantGrid.replaceChildren();
    noResults.hidden = list.length !== 0;

    list.forEach((plant) => {
        const card = document.createElement("article");
        card.className = "plant-card";

        // สร้างองค์ประกอบรูปภาพของการ์ด
        const img = document.createElement("img");
        img.className = "plant-card-img";
        img.src = plant.image;
        img.alt = plant.name;
        img.loading = "lazy";
        // ถ้าโหลดรูปจริงไม่สำเร็จ ให้ใช้รูป Placeholder แสดงแทน
        img.onerror = () => {
            img.src = getPlaceholderImage(plant.name);
        };

        const info = document.createElement("div");
        info.className = "plant-info";

        const title = document.createElement("h3");
        title.textContent = plant.name;

        const codeTag = document.createElement("p");
        codeTag.className = "plant-code";
        codeTag.textContent = `รหัส: ${plant.code}`;

        const categoryText = document.createElement("p");
        categoryText.className = "plant-category-text";
        categoryText.textContent = `ประเภท: ${plant.category} | วงศ์: ${plant.family}`;

        const button = document.createElement("button");
        button.type = "button";
        button.textContent = "ดูรายละเอียด →";
        button.addEventListener("click", () => showDetails(plant));

        info.append(title, codeTag, categoryText, button);
        card.append(img, info);
        plantGrid.append(card);
    });
}

// กรองข้อมูลตามคำค้นหาและประเภท
function filterPlants() {
    const keyword = searchInput.value.trim().toLowerCase();

    const results = plants.filter((plant) => {
        const matchesKeyword = [
            plant.name,
            plant.code,
            plant.scientific,
            plant.family,
            plant.category,
            plant.features,
            plant.location,
            plant.benefit,
            plant.origin
        ].some((value) => value.toLowerCase().includes(keyword));

        const matchesCategory =
            selectedCategory === "ทั้งหมด" ||
            plant.category === selectedCategory;

        return matchesKeyword && matchesCategory;
    });

    displayPlants(results);
}

// Event Listeners
searchForm.addEventListener("submit", (event) => {
    event.preventDefault();
    filterPlants();
    document.getElementById("plants").scrollIntoView({
        behavior: "smooth"
    });
});

searchInput.addEventListener("input", filterPlants);

filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
        selectedCategory = button.dataset.category;

        filterButtons.forEach((item) => {
            item.classList.toggle("active", item === button);
        });

        filterPlants();
    });
});

// แสดงรายละเอียดใน Pop-up
function showDetails(plant) {
    plantDetails.replaceChildren();

    const heading = document.createElement("h2");
    heading.textContent = plant.name;

    // สร้างรูปภาพขนาดใหญ่ในหน้าต่าง Pop-up
    const dialogImg = document.createElement("img");
    dialogImg.className = "dialog-plant-img";
    dialogImg.src = plant.image;
    dialogImg.alt = plant.name;
    dialogImg.onerror = () => {
        dialogImg.src = getPlaceholderImage(plant.name);
    };

    const fields = [
        ["รหัสพรรณไม้", plant.code],
        ["ชื่อวิทยาศาสตร์", plant.scientific],
        ["ชื่อวงศ์", plant.family],
        ["ประเภท", plant.category],
        ["ลักษณะเด่น", plant.features],
        ["บริเวณที่พบ", plant.location],
        ["สรรพคุณ", plant.benefit],
        ["ถิ่นกำเนิด", plant.origin]
    ];

    plantDetails.append(heading, dialogImg);

    fields.forEach(([label, value]) => {
        const paragraph = document.createElement("p");
        const strong = document.createElement("strong");
        strong.textContent = label + ": ";

        if (label === "สรรพคุณ") {
            paragraph.append(strong);
            const span = document.createElement("span");
            span.style.whiteSpace = "pre-line";
            span.textContent = value;
            paragraph.append(span);
        } else {
            paragraph.append(strong, document.createTextNode(value));
        }
        
        plantDetails.append(paragraph);
    });

    plantDialog.showModal();
}

